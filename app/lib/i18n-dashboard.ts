export const dashboardDictionaries: Record<Lang, DashboardDict> = { en, fa }

export function useDashboardT() {
  const root = useRouteLoaderData('root') as { lang?: Lang } | undefined
  const { pathname } = useLocation()
  const lang = root?.lang ?? defaultLang(pathname)
  const t = dashboardDictionaries[lang]
  return {
    t,
    lang,
    dir: dirFor(lang),
    n: (value: number) => formatNumber(lang, value),
    digits: (text: string) => localDigits(lang, text),
    percent: (value: number, fractionDigits = 0) => formatPercent(lang, value, fractionDigits),
    millions: (value: number) => t.millions(formatNumber(lang, Math.round(value / 1_000_000))),
  }
}
